def is_yanked(component: str, version: str, *, config=None) -> bool:
    """G6: a yanked version is never bumped to again (the bump engine, E1, calls this)."""
    from nanosoc_rm.versioning.core import yanked_versions
    from nanosoc_rm.versioning.repo import _cfg
    policy, _ = registry_policy(_cfg(config))
    return str(version) in yanked_versions(policy, component)


def allowed(component: str, versions: list[str], *, config=None) -> list[str]:
    """The versions a bump may target: every one of `versions` that is not yanked (G6)."""
    from nanosoc_rm.versioning.core import yanked_versions
    from nanosoc_rm.versioning.repo import _cfg
    policy, _ = registry_policy(_cfg(config))
    y = yanked_versions(policy, component)
    return [v for v in versions if str(v) not in y]


def _silicon_pins(config, component: str, commit: str) -> list[str]:
    """Silicon configurations whose stored tree pins `component` at `commit` (G6: never yanked)."""
    from nanosoc_rm import db
    from nanosoc_rm.analysis import _inputs as inp
    out = []
    try:
        reg = inp.registry(config)
    except Exception:                                              # noqa: BLE001
        return out
    for c in reg.configurations():
        if not c.get("silicon"):
            continue
        for d in db.latest("pin_state", "pin_state:%s:" % c["id"], config=config):
            child = d["fact"].get("child") or {}
            if child.get("component") == component and child.get("commit") == commit:
                out.append(c["id"])
                break
        if c.get("component") == component and c.get("commit") == commit:
            out.append(c["id"])
    return sorted(set(out))


def yank(target: str, version: str, reason: str, by: str, *, config=None, date: str | None = None) -> tuple[dict, str]:
    """G6: (yank_proposal observation, a patch adding the yank to the registry's versioning.yaml). The tag is kept.
    Refused (fact `refused`, empty patch) for a silicon release: a tag silicon/* on the same commit, or a silicon
    configuration pinning it."""
    from nanosoc_rm.versioning import core
    try:
        v = semver.parse(version.lstrip("v"))
    except ValueError as e:
        raise VersioningUsage(str(e)) from None
    if not reason.strip() or not by.strip():
        raise VersioningUsage("a yank needs --reason and --by (who decided it)")
    view = open_repo(target, config=config)
    tags = view.canonical_tags()
    tag = "v%s" % v
    if tag not in tags:
        raise VersioningUsage("%s has no release tag %s on its canonical host" % (target, tag))
    commit = tags[tag]["commit"]
    silicon_tags = sorted(t for t, i in tags.items() if t.startswith("silicon/") and i["commit"] == commit)
    silicon_cfgs = _silicon_pins(view.config, view.target, commit) if view.config else []
    policy, psrc = registry_policy(view.config)
    refused = None
    if silicon_tags or silicon_cfgs:
        refused = "a silicon release is never yanked (G6): %s" % ", ".join(silicon_tags + silicon_cfgs)
    elif str(v) in core.yanked_versions(policy, view.target):
        refused = "%s %s is already yanked" % (view.target, v)
    entry = {"component": view.target, "version": str(v), "tag": tag, "commit": commit, "reason": reason.strip(),
             "by": by.strip(), "date": date or clock.now().date().isoformat()}
    patch = "" if refused else _yank_patch(view.config, policy, entry)
    fact = {"target": view.target, "commit": commit, "ref": tag, "worktree": False, "version": str(v), "tag": tag,
            "entry": entry, "refused": refused, "tag_kept": True, "patch_lines": patch.count("\n")}
    obs = core.observe("yank_proposal", fact, view.sources + psrc, "nanosoc-rm version yank %s %s" % (target, v),
                       subject="yank_proposal:%s:%s" % (view.target, v))
    return obs, patch


def _yank_patch(config, policy: dict, entry: dict) -> str:
    import yaml
    path = "versioning.yaml"
    old = None
    if config is not None:
        try:
            f = Path(config.require("registry", "path")) / path
            old = f.read_text() if f.is_file() else None
        except Exception:                                          # noqa: BLE001
            old = None
    flow = yaml.safe_dump(entry, default_flow_style=True, width=1000, sort_keys=False).strip()
    item = "  - %s\n" % flow
    if old is None:
        new = ("# Registry versioning policy (tool-release#/$defs/versioning_file): yanked releases (G6),\n"
               "# grandfathered tags and the date the C10 tag scheme applies from.\nschema: 1\nyanked:\n" + item)
        body = list(difflib.unified_diff([], new.splitlines(keepends=True), "/dev/null", "b/" + path))
        return "diff --git a/%s b/%s\nnew file mode 100644\n" % (path, path) + "".join(body)
    lines = old.splitlines(keepends=True)
    idx = next((i for i, l in enumerate(lines) if l.rstrip() in ("yanked:", "yanked: []")), None)
    if idx is None:
        new_lines = lines + ([] if not lines or lines[-1].endswith("\n") else ["\n"]) + ["yanked:\n", item]
    elif lines[idx].rstrip() == "yanked: []":
        new_lines = lines[:idx] + ["yanked:\n", item] + lines[idx + 1:]
    else:
        # the existing list's own indent (YAML allows `- ` at column 0 under `yanked:`): the new item matches it,
        # so the result never mixes indentations (review item 7)
        j = idx + 1
        first = next((l for l in lines[j:] if l.strip() and not l.lstrip().startswith("#")), "")
        indent = first[:len(first) - len(first.lstrip())] if first.lstrip().startswith("- ") else "  "
        item = "%s- %s\n" % (indent, flow)
        while j < len(lines) and (not lines[j].strip() or lines[j].startswith(("  ", "\t"))
                                  or (indent == "" and lines[j].startswith("- "))):
            j += 1
        new_lines = lines[:j] + [item] + lines[j:]
    new = "".join(new_lines)
    try:
        doc = contracts.load_yaml(new)
    except Exception as e:                                         # noqa: BLE001 - never a traceback (exit 2)
        raise VersioningError("the yank patch would not parse as YAML (%s): edit versioning.yaml by hand"
                              % str(e).splitlines()[0]) from None
    if contracts.validate("tool-release", doc, "/$defs/versioning_file"):
        raise VersioningError("the yank patch would break versioning.yaml's contract")
    return _diff(path, old, new)
