def _consumers(config, component: str) -> list[dict]:
    """Registered configurations whose stored tree pins `component`, with their latest stored local compat run."""
    from nanosoc_rm import db
    out = []
    if config is None:
        return out
    try:
        from nanosoc_rm.ci import configs
        confs = [c["id"] for c in configs.configurations(config)]
    except Exception:                                              # noqa: BLE001 - no registry: no consumers
        return out
    for cid in confs:
        pins = [d for d in db.latest("pin_state", "pin_state:%s:" % cid, config=config)
                if (d["fact"].get("child") or {}).get("component") == component]
        if not pins:
            continue
        runs = db.latest("compat_result", "compat_result:%s:" % cid, config=config)
        last = max(runs, key=lambda d: d["observed_at"]) if runs else None
        out.append({"configuration": cid, "pins": sorted({p["fact"]["child"]["commit"] for p in pins if p["fact"]["child"].get("commit")}),
                    "last_compat": ({"verdict": last["fact"].get("run_verdict") or last["fact"]["verdict"],
                                     "at": last["observed_at"], "subject": last["subject"]} if last else None)})
    return out


def _defects(view, base_commit: str | None) -> list[dict]:
    """Registry defects that touch the component: fixed or introduced between the baseline and the head, or open."""
    if view.registry is None:
        return []
    out = []
    for d in view.registry._defects.values():                     # noqa: SLF001 - the analysis registry's records
        cites = [c for c in d.get("origin") or [] if c["component"] == view.target]
        fixed = [(f["id"], c) for f in d.get("forms") or [] for c in f.get("fixed_in") or [] if c["component"] == view.target]
        if d.get("component") != view.target and not cites and not fixed:
            continue
        in_range = lambda c: (view.is_ancestor(c, view.commit) is True and
                              (base_commit is None or view.is_ancestor(c, base_commit) is False))
        row = {"id": d["id"], "title": d.get("title"),
               "fixed_here": sorted({form for form, c in fixed if in_range(c["commit"])}),
               "introduced_here": [c["commit"] for c in cites if in_range(c["commit"])],
               "open_forms": [f["id"] for f in d.get("forms") or [] if not f.get("fixed_in")]}
        out.append(row)
    return out


def _submodules(view) -> list[dict]:
    from nanosoc_rm.quality.source import parse_gitmodules
    from nanosoc_rm.versioning.manifest import _tags_at
    from nanosoc_rm.versioning.repo import component_for_url
    gm = view.head_text(".gitmodules") or ""
    urls, cur = {}, None
    for line in gm.splitlines():
        s = line.strip()
        if s.startswith("[submodule"):
            cur = s.split('"')[1] if '"' in s else None
        elif s.startswith("url") and "=" in s and cur:
            urls[cur] = s.split("=", 1)[1].strip()
    links = view.gitlinks(view.commit) if view.commit else {}
    out = []
    for name, path in sorted(parse_gitmodules(gm).items(), key=lambda x: x[1]):
        if path not in links:
            continue
        cid = component_for_url(urls.get(name, ""), view.config, view.registry, view.canonical)
        out.append({"path": path, "component": cid, "commit": links[path],
                    "release_tags": _tags_at(view, cid, links[path]) if cid else []})
    return out


def _rewrite_version(text: str, path: str, new: str) -> str | None:
    """The file with its version set to `new`: the manifest's `version:` or pyproject's [project] version."""
    lines = text.splitlines(keepends=True)
    in_project = path != "pyproject.toml"
    for i, line in enumerate(lines):
        s = line.strip()
        if path == "pyproject.toml" and s.startswith("["):
            in_project = s == "[project]"
            continue
        if in_project and (s.startswith("version:") or s.startswith("version =") or s.startswith("version=")):
            indent = line[: len(line) - len(line.lstrip())]
            nl = "\n" if line.endswith("\n") else ""
            lines[i] = ('%sversion: "%s"%s' % (indent, new, nl)) if path != "pyproject.toml" else \
                ('%sversion = "%s"%s' % (indent, new, nl))
            return "".join(lines)
    return None


def _diff(path: str, old: str, new: str) -> str:
    body = list(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                     "a/" + path, "b/" + path))
    return ("diff --git a/%s b/%s\n" % (path, path) + "".join(body)) if body else ""


def draft(target: str, out_dir=None, *, config=None, date: str | None = None, regenerator=None) -> dict:
    """G1: write the release draft folder for `target`'s next version (from `version next`). Returns the
    tool_release_draft observation. VersioningUsage when there is nothing to release or out_dir is not empty; VersioningRefused (exit 1) while
    the plan has findings (C9 refusing 1.0.0, a version already tagged or yanked, a changelog that fails lint)."""
    from nanosoc_rm.versioning import core
    view = open_repo(target, config=config)
    policy, psrc = registry_policy(view.config)
    fact_plan = core._plan(view, policy, regenerator)
    nxt = fact_plan["next"]["version"]
    if not nxt:
        raise VersioningUsage("no release to draft for %s: %s" % (target, fact_plan["next"]["reason"]))
    if fact_plan["findings"]:                                       # review item 1: a FAIL plan is never drafted
        raise VersioningRefused("no release draft of %s %s while `version next` has findings (FAIL): %s"
                                % (view.target, nxt, "; ".join(fact_plan["findings"])))
    klass = fact_plan["classification"]["class"]
    date = date or clock.now().date().isoformat()
    if out_dir is None:
        if view.config is None:
            raise VersioningUsage("give --out DIR (no service config, so no data directory)")
        out_dir = view.config.data_dir / "drafts" / view.target / nxt
    out = Path(out_dir)
    if out.exists() and any(out.iterdir()):
        raise VersioningUsage("%s is not empty: a draft is written only into a new or empty directory" % out)
    prev_tag = fact_plan["current"]["tag"]
    # version.patch: CHANGELOG (Unreleased -> [X.Y.Z]), manifest version, pyproject version
    patches, changed = [], []
    text = view.head_text(cl.FILE)
    rel_section = ""
    if text is not None and cl.parse(text).unreleased is not None:
        new = cl.release(text, nxt, date, previous_tag=prev_tag if fact_plan["current"]["kind"] == "release" else None,
                         compare_base=view.base_url)
        patches.append(_diff(cl.FILE, text, new))
        changed.append(cl.FILE)
        rel_section = _section_text(new, nxt)
    for path in (mf.FILE, "pyproject.toml"):
        t = view.head_text(path)
        if t is None:
            continue
        n = _rewrite_version(t, path, nxt)
        if n is not None and n != t:
            patches.append(_diff(path, t, n))
            changed.append(path)
    consumers = _consumers(view.config, view.target)
    build = next((s for s in fact_plan["classification"]["signals"] if s["signal"] == "build"), {})
    gates = [{"tier": t, "on": [c["configuration"] for c in consumers[:1]] or None,
              "required": True, "evidence": (consumers[0]["last_compat"] if consumers and t == "t0" else None)}
             for t in ("t0", "t1", "t2")]
    gates.append({"tier": "t3", "on": [c["configuration"] for c in consumers[:1]] or None,
                  "required": True if build.get("build_affecting") is not False else False,
                  "evidence": None,
                  "why": ("build-affecting (C7)" if build.get("build_affecting") else
                          "build-affecting unmeasured (C7 needs the generator): T3 required until shown otherwise"
                          if build.get("build_affecting") is None else "not build-affecting")})
    release = {
        "schema": 1,
        "component": view.target,
        "version": nxt,
        "candidate_tag": "v%s-rc.1" % nxt,
        "final_tag": "v%s" % nxt,
        "previous": {"tag": prev_tag, "kind": fact_plan["current"]["kind"]},
        "head": view.commit,
        "class": klass,
        "class_status": fact_plan["classification"]["status"],
        "class_reason": fact_plan["classification"]["reason"],
        "date": date,
        "changelog": fact_plan["unreleased"],
        "submodules": _submodules(view),
        "defects": _defects(view, fact_plan["current"]["commit"]),
        "consumers": consumers,
        "gates": gates,
        "approvals": approvals_for(view.target, klass),
        "artefacts": _artefacts(view.target, nxt, changed),
        "patch_files": changed,
        "generated_at": clock.iso(),
        "pushed": False,
    }
    problems = contracts.validate("tool-release", release)
    if problems:
        raise ValueError("the draft breaks tool-release: %s" % "; ".join(problems[:6]))
    out.mkdir(parents=True, exist_ok=True)
    (out / "release.json").write_text(json.dumps(release, indent=1, sort_keys=False) + "\n")
    (out / "version.patch").write_text("".join(patches))
    (out / "CHANGELOG.release.md").write_text(rel_section or "(no CHANGELOG.md [Unreleased] section to release)\n")
    (out / "commands.txt").write_text(_commands(release, view))
    (out / "README.md").write_text(_readme(release, view))
    fact = {"target": view.target, "commit": view.commit, "ref": view.ref, "worktree": view.worktree,
            "version": nxt, "class": klass, "class_status": release["class_status"], "dir": str(out),
            "files": list(DRAFT_FILES), "approvals": release["approvals"], "gates": gates, "pushed": False}
    return core.observe("tool_release_draft", fact, view.sources + psrc, "nanosoc-rm version draft %s" % target,
                        subject="tool_release_draft:%s:%s" % (view.target, nxt))


def _section_text(text: str, version: str) -> str:
    lines, keep = [], False
    for line in text.splitlines():
        if line.startswith("## "):
            keep = line.startswith("## [%s]" % version)
        if keep:
            lines.append(line)
    return "\n".join(lines).strip() + "\n"


def _artefacts(component: str, version: str, changed: list[str]) -> list[dict]:
    """G1 artefacts: source archive with submodules, manifest, changelog, test evidence, a wheel for nanosoc_gen."""
    arts = [{"name": "source archive with submodules", "file": "%s-%s-src.tar.gz" % (component, version)},
            {"name": "manifest", "file": mf.FILE},
            {"name": "changelog", "file": cl.FILE},
            {"name": "test evidence", "file": "evidence/ (T0-T2 results; T3 if build-affecting)"}]
    if component == "nanosoc_gen" or "pyproject.toml" in changed:
        arts.append({"name": "wheel", "file": "%s-%s-py3-none-any.whl" % (component.replace("-", "_"), version)})
    return arts


def _commands(r: dict, view) -> str:
    rc, final = r["candidate_tag"], r["final_tag"]
    lines = ["# " + NOT_PUSHED,
             "# Release %s %s (class %s, %s). Run in a clean clone of the canonical repo, after review." % (
                 r["component"], r["version"], r["class"], r["class_status"]),
             "",
             "git apply --index version.patch",
             'git commit -m "release: %s %s" -m "Requirements: G1"' % (r["component"], r["version"]),
             "# open the release PR with this folder's README.md as its description (G1); merge after the gates",
             "# candidate (G5: %s)" % ", ".join(r["approvals"][0]["roles"]),
             'git tag -a %s -m "%s %s candidate 1"' % (rc, r["component"], r["version"]),
             "# gates on the candidate, for at least one SoC that uses it (G1):"]
    for g in r["gates"]:
        on = (g["on"] or ["<configuration that uses %s>" % r["component"]])[0]
        if g["required"] and g["tier"] == "t3":
            lines.append("# T3 (build-affecting regression) on %s: run by a person or CI; no local T3 runner yet" % on)
        elif g["required"]:
            lines.append("nanosoc-rm compat %s --pin <tree path of %s>=<candidate sha>%s" % (
                on, r["component"], "" if g["tier"] == "t0" else " --tier %s" % g["tier"]))
    lines += ["# final (G5: %s)" % ", ".join(r["approvals"][-1]["roles"]),
              'git tag -a %s -m "%s %s"' % (final, r["component"], r["version"]),
              "# push the tags to the CANONICAL host only (C10); a release tag is never moved or deleted",
              "# git push <canonical remote> %s %s" % (rc, final)]
    return "\n".join(lines) + "\n"


def _readme(r: dict, view) -> str:
    rows = "\n".join("| %s | %s | %s | %s |" % (a["step"], ", ".join(a["roles"]), a.get("condition") or "",
                                               a["state"]) for a in r["approvals"])
    subs = "\n".join("| `%s` | %s | `%s` | %s |" % (s["path"], s["component"] or "unknown", s["commit"][:12],
                                                  ", ".join(s["release_tags"]) or "untagged") for s in r["submodules"]) \
        or "| (none) | | | |"
    defs = "\n".join("- %s %s: fixed here %s; introduced here %s; open forms %s" % (
        d["id"], d["title"] or "", ", ".join(d["fixed_here"]) or "none", ", ".join(c[:12] for c in d["introduced_here"])
        or "none", ", ".join(d["open_forms"]) or "none") for d in r["defects"]) or "- none recorded in the registry"
    gates = "\n".join("- %s on %s: %s%s" % (g["tier"].upper(), ", ".join(g["on"] or ["a SoC that uses it (none walked)"]),
                                            "required" if g["required"] else "not required",
                                            " (%s)" % g["why"] if g.get("why") else "") for g in r["gates"])
    log = "\n".join("### %s\n" % c + "\n".join("- %s" % e for e in r["changelog"][c])
                    for c in reversed(semver.CLASSES + ("unclassed",)) if r["changelog"].get(c))
    return """# Release draft: %(component)s %(version)s

> %(np)s

- Version: **%(version)s** (previous %(prev)s), class **%(class)s** (%(status)s%(reason)s)
- Head: `%(head)s`. Candidate tag `%(rc)s`, final tag `%(final)s` (C10: annotated, canonical host only).
- Files: `version.patch` (CHANGELOG, manifest, pyproject versions), `CHANGELOG.release.md`, `release.json`
  (contract: schemas/tool-release.schema.json), `commands.txt` (for a person).

## Changelog (classed, C2)

%(log)s

## Gates (G1)

%(gates)s

## Approvals (G5)

| Step | Roles (all needed) | Condition | State |
|---|---|---|---|
%(rows)s

Record a person's approval with `nanosoc-rm version approve <this folder> --step <step> --login <login>`; the
login's roles come from the service config `[roles]`.

## Submodules

| Path | Component | Pinned | Release tags at the pin |
|---|---|---|---|
%(subs)s

## Defects (registry)

%(defs)s
""" % {"component": r["component"], "version": r["version"], "np": NOT_PUSHED,
       "prev": r["previous"]["tag"] or "none", "class": r["class"], "status": r["class_status"],
       "reason": ": " + r["class_reason"] if r["class_reason"] else "", "head": r["head"], "rc": r["candidate_tag"],
       "final": r["final_tag"], "log": log or "(no classed entries)", "gates": gates, "rows": rows, "subs": subs,
       "defs": defs}


