"""Tool releases (G1), their approvals (G5) and yanks (G6): files and patches for a person, never a write.

    draft(target, out_dir, *, config, date, regenerator) -> tool_release_draft observation
        writes a draft FOLDER (only under out_dir): README.md, release.json (tool-release schema), version.patch,
        CHANGELOG.release.md, commands.txt. Nothing is tagged, pushed or opened: the README and commands.txt say so.
    approve(draft_dir, step, login, *, config) -> the updated approval record (G5, roles from the service config)
    yank(target, version, reason, by, *, config) -> (yank_proposal observation, registry patch)
    is_yanked(component, version, *, config) / allowed(component, versions, *, config)  for the bump engine (E1)

G5 approval matrix (APPROVAL_MATRIX): tool candidate by the bot; tool final (fix or feature) by the bot once T3
passes; tool final (breaking) by an owner and David; SoC release or train by David; a tapeout SoC release or an
errata revision by David and a second reviewer. Roles come from the service config `[roles]`: `release-manager`
(David), `reviewer` (the second reviewer), `owner:<component>`. The bot's steps stay pending while the Phase 3 gate
is not met: the bot is automation, and automation ships disabled (CR-15).
"""
from __future__ import annotations

import difflib
import json
import os
from pathlib import Path

from nanosoc_rm import clock, contracts
from nanosoc_rm.versioning import changelog as cl
from nanosoc_rm.versioning import manifest as mf
from nanosoc_rm.versioning import semver
from nanosoc_rm.versioning.repo import (VersioningError, VersioningRefused, VersioningUsage, open_repo,
                                        registry_policy)

__all__ = ["APPROVAL_MATRIX", "BOT", "draft", "approve", "yank", "is_yanked", "allowed", "approvals_for",
           "DRAFT_FILES", "NOT_PUSHED"]

BOT = "bot"
NOT_PUSHED = ("Generated by nanosoc-rm for a person. Nothing was tagged, pushed, merged or opened: every command "
              "below is for a person to run after review.")
DRAFT_FILES = ("README.md", "release.json", "version.patch", "CHANGELOG.release.md", "commands.txt")
# G5: who approves what. `roles`: every one is needed (all-of); `bot` is the automation identity.
APPROVAL_MATRIX = [
    {"step": "tool-candidate", "what": "tool release candidate tag vX.Y.Z-rc.N", "roles": [BOT], "condition": None},
    {"step": "tool-final", "what": "tool final tag, fix or feature", "roles": [BOT], "condition": "T3 PASS on the candidate"},
    {"step": "tool-final-breaking", "what": "tool final tag, breaking", "roles": ["owner:{component}", "release-manager"],
     "condition": None},
    {"step": "soc-release", "what": "SoC release or train", "roles": ["release-manager"], "condition": None},
    {"step": "soc-tapeout", "what": "tapeout SoC release or errata revision", "roles": ["release-manager", "reviewer"],
     "condition": None},
]


def approvals_for(component: str, change_class: str) -> list[dict]:
    """The G5 steps a tool release of `change_class` needs, each {step, what, roles, condition, approvals: []}."""
    final = "tool-final-breaking" if change_class == "breaking" else "tool-final"
    out = []
    for row in APPROVAL_MATRIX:
        if row["step"] in ("tool-candidate", final):
            out.append({"step": row["step"], "what": row["what"],
                        "roles": [r.format(component=component) for r in row["roles"]],
                        "condition": row["condition"], "approvals": [],
                        "state": "pending"})
    for a in out:
        if BOT in a["roles"]:
            a["state"] = "automation-disabled"
            a["note"] = ("the bot is automation; it stays disabled until the Phase 3 entry gate is met "
                         "(docs/phase-gates.yaml, CR-15). Until then this step is not approved by anyone.")
    return out


